// ──────────────────────────────────────────────────────────────────────────────
// @reqnx/redis — Build Lua Scripts
//
// Concatenates shared Lua helpers with algorithm script bodies and emits
// packages/redis/src/scripts/generated.ts with embedded scripts and SHA1 hashes.
// ──────────────────────────────────────────────────────────────────────────────

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const ROOT = resolve(__dirname, '..');
const LUA_DIR = join(ROOT, 'src', 'lua');
const SHARED_DIR = join(LUA_DIR, 'shared');
const OUT_FILE = join(ROOT, 'src', 'scripts', 'generated.ts');

const SHARED_FILES = ['exact_math.lua', 'time.lua', 'validation.lua', 'result.lua'];

function computeSha1(content: string): string {
  return createHash('sha1').update(content).digest('hex');
}

function loadSharedLua(): string {
  return SHARED_FILES.map((file) => {
    const fullPath = join(SHARED_DIR, file);
    if (!existsSync(fullPath)) {
      throw new Error(`Missing required shared Lua module: ${fullPath}`);
    }
    return readFileSync(fullPath, 'utf8').trim();
  }).join('\n\n');
}

interface ScriptBundle {
  name: string;
  varPrefix: string;
  consumeScript: string;
  consumeSha: string;
  peekScript: string;
  peekSha: string;
}

function toConstantPrefix(filename: string): string {
  return filename
    .replace(/\.lua$/, '')
    .toUpperCase()
    .replace(/-/g, '_');
}

function build(): string {
  const shared = loadSharedLua();
  const luaFiles = readdirSync(LUA_DIR)
    .filter((f) => f.endsWith('.lua'))
    .sort();

  const bundles: ScriptBundle[] = [];

  for (const file of luaFiles) {
    const body = readFileSync(join(LUA_DIR, file), 'utf8').trim();
    const varPrefix = toConstantPrefix(file);

    const consumeScript = `local IS_PEEK = false\n\n${shared}\n\n${body}\n`;
    const peekScript = `#!lua flags=no-writes\nlocal IS_PEEK = true\n\n${shared}\n\n${body}\n`;

    bundles.push({
      name: file,
      varPrefix,
      consumeScript,
      consumeSha: computeSha1(consumeScript),
      peekScript,
      peekSha: computeSha1(peekScript),
    });
  }

  const lines: string[] = [
    '// ──────────────────────────────────────────────────────────────────────────────',
    '// @reqnx/redis — Generated Lua Script Constants (DO NOT EDIT DIRECTLY)',
    '//',
    '// Generated by `pnpm --filter @reqnx/redis build:lua`.',
    '// ──────────────────────────────────────────────────────────────────────────────',
    '',
  ];

  for (const b of bundles) {
    lines.push(`/** Raw Lua consume script for ${b.name}. */`);
    lines.push(`export const ${b.varPrefix}_CONSUME_SCRIPT = ${JSON.stringify(b.consumeScript)};`);
    lines.push(`export const ${b.varPrefix}_CONSUME_SHA = ${JSON.stringify(b.consumeSha)};`);
    lines.push('');
    lines.push(`/** Raw Lua peek script for ${b.name} (flags=no-writes). */`);
    lines.push(`export const ${b.varPrefix}_PEEK_SCRIPT = ${JSON.stringify(b.peekScript)};`);
    lines.push(`export const ${b.varPrefix}_PEEK_SHA = ${JSON.stringify(b.peekSha)};`);
    lines.push('');
  }

  return lines.join('\n');
}

const isCheck = process.argv.includes('--check');
const output = build();

if (isCheck) {
  if (!existsSync(OUT_FILE)) {
    console.error(`Missing generated file: ${OUT_FILE}`);
    process.exit(1);
  }
  const current = readFileSync(OUT_FILE, 'utf8');
  if (current !== output) {
    console.error(
      `Generated Lua scripts are out of date! Run 'pnpm --filter @reqnx/redis build:lua' to regenerate.`,
    );
    process.exit(1);
  }
  console.log('Generated Lua scripts are fresh.');
} else {
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, output, 'utf8');
  console.log(`Generated ${OUT_FILE}`);
}
